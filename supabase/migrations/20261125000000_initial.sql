  using (id = (select auth.uid()) or private.is_owner());
create policy categories_write on public.categories for all to authenticated
  using (private.is_owner()) with check (private.is_owner());
create policy products_write on public.products for all to authenticated
  using (private.is_owner()) with check (private.is_owner());
create policy storage_write on public.storage_units for all to authenticated
  using (private.is_owner()) with check (private.is_owner());
create policy orders_insert on public.bulk_orders for insert to authenticated
  with check (private.is_active());
create policy orders_update on public.bulk_orders for update to authenticated
  using (private.is_active()) with check (private.is_active());
create policy alerts_update on public.alerts for update to authenticated
  using (private.is_active()) with check (private.is_active());
create policy audit_insert on public.audit_log for insert to authenticated
  with check (private.is_active() and user_id = (select auth.uid()));

