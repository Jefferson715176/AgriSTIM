-- AgriSTIM on Supabase PostgreSQL. Run with Supabase migrations or SQL Editor.
create schema if not exists private;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null default '',
  role text not null default 'staff' check (role in ('owner', 'staff')),
  active boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, email, full_name)
  values (new.id, coalesce(new.email, ''), coalesce(new.raw_user_meta_data->>'full_name', ''));
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function private.is_active() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles where id = (select auth.uid()) and active);
$$;
create or replace function private.is_owner() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles where id = (select auth.uid()) and active and role = 'owner');
$$;
revoke all on function private.is_active() from public;
revoke all on function private.is_owner() from public;
grant usage on schema private to authenticated;
grant execute on function private.is_active(), private.is_owner() to authenticated;

create table public.categories (
  id integer generated by default as identity primary key,
  name varchar(50) not null unique
);
create table public.products (
  id integer generated by default as identity primary key,
  name varchar(120) not null,
  category varchar(50) not null references public.categories(name) on update cascade,
  unit varchar(20) not null,
  cost_price numeric(10,2) not null default 0 check (cost_price >= 0),
  retail_price numeric(10,2) not null default 0 check (retail_price >= 0),
  bulk_price numeric(10,2) not null default 0 check (bulk_price >= 0),
  reorder_level integer not null default 5 check (reorder_level >= 0),
  archived boolean not null default false
);
create unique index products_active_name_unique on public.products(lower(name)) where archived = false;
create table public.storage_units (
  id integer generated by default as identity primary key,
  name varchar(80) not null,
  device_id varchar(40) not null unique,
  min_c numeric(5,2) not null,
  max_c numeric(5,2) not null,
  constraint temperature_range check (min_c < max_c and min_c >= -60 and max_c <= 100)
);
create table public.batches (
  id integer generated by default as identity primary key,
  product_id integer not null references public.products(id),
  batch_no varchar(40) not null,
  supplier varchar(100),
  unit_id integer references public.storage_units(id) on delete set null,
  qty_received integer not null check (qty_received > 0),
  qty_remaining integer not null check (qty_remaining >= 0 and qty_remaining <= qty_received),
  expiry date,
  received_at timestamptz not null default now()
);
create index batches_product_expiry on public.batches(product_id, expiry, id) where qty_remaining > 0;
create table public.sales (
  id integer generated by default as identity primary key,
  type text not null check (type in ('retail', 'bulk')),
  customer varchar(100),
  total numeric(12,2) not null check (total >= 0),
  user_id uuid references public.profiles(id) on delete set null,
  legacy_user_id integer,
  created_at timestamptz not null default now()
);
create table public.sale_items (
  id integer generated by default as identity primary key,
  sale_id integer not null references public.sales(id) on delete cascade,
  product_id integer references public.products(id),
  qty integer not null check (qty > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  unit_cost numeric(10,2) not null check (unit_cost >= 0)
);
create table public.losses (
  id integer generated by default as identity primary key,
  product_id integer references public.products(id),
  qty integer not null check (qty > 0),
  reason text not null check (reason in ('expired', 'damaged', 'spoiled')),
  amount numeric(10,2) not null check (amount >= 0),
  created_at timestamptz not null default now()
);
create table public.bulk_orders (
  order_id integer generated by default as identity primary key,
  order_number varchar(50) not null unique,
  customer_name varchar(150) not null,
  contact_number varchar(30),
  order_date timestamptz not null default now(),
  pickup_date date,
  pickup_time time,
  total_amount numeric(12,2) not null default 0 check (total_amount >= 0),
  order_status text not null default 'Pending' check (order_status in ('Pending','Confirmed','Preparing','Ready for Pickup','Completed','Cancelled')),
  payment_status text not null default 'Unpaid' check (payment_status in ('Unpaid','Partially Paid','Paid')),
  notes text,
  created_at timestamptz not null default now()
);
create table public.alerts (
  id integer generated by default as identity primary key,
  type text not null check (type in ('temp', 'offline', 'low_stock', 'expiry')),
  ref_id integer,
  message varchar(255) not null,
  status text not null default 'open' check (status in ('open', 'ack', 'resolved')),
  remarks varchar(255),
  constraint resolution_needs_remarks check (status <> 'resolved' or nullif(trim(remarks), '') is not null),
  created_at timestamptz not null default now()
);
create unique index alerts_unresolved_unique on public.alerts(type, ref_id) where status <> 'resolved';
create table public.temp_logs (
  id bigint generated by default as identity primary key,
  unit_id integer not null references public.storage_units(id) on delete cascade,
  temp_c numeric(5,2) not null check (temp_c between -60 and 100),
  humidity numeric(5,2) check (humidity between 0 and 100),
  logged_at timestamptz not null default now()
);
create index temp_logs_unit_time on public.temp_logs(unit_id, logged_at desc);
create table public.price_list (
  id integer generated by default as identity primary key,
  category varchar(50) not null,
  brand varchar(50),
  product_name varchar(100) not null,
  variant varchar(50),
  price_per_kilo numeric(10,2),
  price_per_sack numeric(10,2),
  price_half_sack numeric(10,2),
  price_per_piece numeric(10,2),
  price_tie_by_10s numeric(10,2),
  needs_review boolean not null default false
);
create table public.audit_log (
  id integer generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  legacy_user_id integer,
  action varchar(255) not null,
  created_at timestamptz not null default now()
);

