-- Void sales, bulk orders with reserved stock, and scheduled alert refresh.

-- Which batches each sale drew from, so a void can return stock to the same batches.
create table public.sale_batches (
  sale_id integer not null references public.sales(id) on delete cascade,
  batch_id integer not null references public.batches(id),
  qty integer not null check (qty > 0),
  primary key (sale_id, batch_id)
);
alter table public.sale_batches enable row level security;

alter table public.sales
  add column voided_at timestamptz,
  add column voided_by uuid references public.profiles(id) on delete set null,
  add column void_reason varchar(255);

create table public.bulk_order_items (
  id integer generated by default as identity primary key,
  order_id integer not null references public.bulk_orders(order_id) on delete cascade,
  product_id integer not null references public.products(id),
  qty integer not null check (qty > 0 and qty <= 1000000),
  unit_price numeric(10,2) not null check (unit_price >= 0)
);
create index bulk_order_items_product on public.bulk_order_items(product_id);
alter table public.bulk_order_items enable row level security;
create policy read_active on public.bulk_order_items for select to authenticated using (private.is_active());
grant select on public.bulk_order_items to authenticated;

alter table public.bulk_orders add column sale_id integer references public.sales(id);

-- Sellable stock minus what open pickup orders have reserved.
create or replace function private.free_stock(p_product_id integer) returns integer
language sql stable security definer set search_path = '' as $$
  select (coalesce((select sum(qty_remaining) from public.batches
                    where product_id = p_product_id and qty_remaining > 0
                      and (expiry is null or expiry >= private.today())), 0)
        - coalesce((select sum(i.qty) from public.bulk_order_items i
                    join public.bulk_orders o on o.order_id = i.order_id
                    where i.product_id = p_product_id
                      and o.order_status not in ('Completed','Cancelled')), 0))::integer
$$;

create or replace function public.record_sale(p_type text, p_customer text, p_items jsonb)
returns integer language plpgsql security definer set search_path = '' as $$
declare
  v_sale_id integer; v_product public.products%rowtype; v_batch public.batches%rowtype;
  v_item record; v_remaining integer; v_take integer; v_price numeric(10,2); v_total numeric(12,2) := 0;
begin
  if not private.is_active() then raise exception 'Not authorized'; end if;
  if p_type not in ('retail','bulk') or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Invalid sale';
  end if;
  if length(coalesce(p_customer,'')) > 100 then raise exception 'Customer name too long'; end if;
  insert into public.sales(type,customer,total,user_id)
  values(p_type,nullif(trim(p_customer),''),0,auth.uid()) returning id into v_sale_id;
  for v_item in
    select product_id, sum(qty)::integer as qty
    from jsonb_to_recordset(p_items) as x(product_id integer, qty integer)
    group by product_id order by product_id
  loop
    if v_item.product_id is null or v_item.qty < 1 or v_item.qty > 1000000 then raise exception 'Invalid quantity'; end if;
    select * into v_product from public.products where id = v_item.product_id and not archived for update;
    if not found then raise exception 'Product unavailable'; end if;
    if private.free_stock(v_item.product_id) < v_item.qty then
      raise exception 'Insufficient stock for % (some may be reserved for pickup orders)', v_product.name;
    end if;
    v_remaining := v_item.qty;
    for v_batch in
      select * from public.batches
      where product_id = v_item.product_id and qty_remaining > 0 and (expiry is null or expiry >= private.today())
      order by expiry nulls last, id for update
    loop
      exit when v_remaining = 0;
      v_take := least(v_remaining,v_batch.qty_remaining);
      update public.batches set qty_remaining = qty_remaining - v_take where id = v_batch.id;
      insert into public.sale_batches(sale_id,batch_id,qty) values(v_sale_id,v_batch.id,v_take);
      v_remaining := v_remaining - v_take;
    end loop;
    if v_remaining > 0 then raise exception 'Insufficient stock for %', v_product.name; end if;
    v_price := case when p_type = 'bulk' and v_product.bulk_price > 0 then v_product.bulk_price else v_product.retail_price end;
    insert into public.sale_items(sale_id,product_id,qty,unit_price,unit_cost)
    values(v_sale_id,v_item.product_id,v_item.qty,v_price,v_product.cost_price);
    v_total := v_total + v_item.qty * v_price;
  end loop;
  update public.sales set total = v_total where id = v_sale_id;
  insert into public.audit_log(user_id,action) values(auth.uid(),'sale #' || v_sale_id || ' ' || p_type);
  return v_sale_id;
end;
$$;

create or replace function public.void_sale(p_sale_id integer, p_reason text)
returns void language plpgsql security definer set search_path = '' as $$
declare v_sale public.sales%rowtype;
begin
  if not private.is_owner() then raise exception 'Only the owner can void sales'; end if;
  if length(trim(coalesce(p_reason,''))) not between 1 and 255 then raise exception 'Give a reason for the void'; end if;
  select * into v_sale from public.sales where id = p_sale_id for update;
  if not found then raise exception 'Sale not found'; end if;
  if v_sale.voided_at is not null then raise exception 'Sale is already voided'; end if;
  if not exists(select 1 from public.sale_batches where sale_id = p_sale_id) then
    raise exception 'This sale was recorded before voiding was available, so its stock cannot be returned automatically';
  end if;
  update public.batches b set qty_remaining = b.qty_remaining + sb.qty
  from public.sale_batches sb where sb.sale_id = p_sale_id and b.id = sb.batch_id;
  update public.sales set voided_at = now(), voided_by = auth.uid(), void_reason = trim(p_reason) where id = p_sale_id;
  insert into public.audit_log(user_id,action) values(auth.uid(), left('voided sale #' || p_sale_id || ': ' || trim(p_reason), 255));
end;
$$;

-- Orders now list products; the total is computed and the stock is reserved until pickup.
drop function public.create_bulk_order(text,text,date,time,numeric,text);
create function public.create_bulk_order(
  p_customer_name text, p_contact_number text, p_pickup_date date,
  p_pickup_time time, p_items jsonb, p_notes text
) returns integer language plpgsql security definer set search_path = '' as $$
declare v_id integer; v_item record; v_product public.products%rowtype; v_price numeric(10,2); v_total numeric(12,2) := 0;
begin
  if not private.is_active() then raise exception 'Not authorized'; end if;
  if length(trim(coalesce(p_customer_name,''))) not between 1 and 150
     or length(coalesce(p_contact_number,'')) > 30 or length(coalesce(p_notes,'')) > 1000
     or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Invalid bulk order';
  end if;
  v_id := nextval(pg_get_serial_sequence('public.bulk_orders','order_id'));
  insert into public.bulk_orders(order_id,order_number,customer_name,contact_number,pickup_date,pickup_time,total_amount,notes)
  values(v_id,'BO-' || to_char(now() at time zone 'Asia/Manila','YYYYMMDD') || '-' || lpad(v_id::text,6,'0'),
         trim(p_customer_name),nullif(trim(p_contact_number),''),p_pickup_date,p_pickup_time,0,nullif(trim(p_notes),''));
  for v_item in
    select product_id, sum(qty)::integer as qty
    from jsonb_to_recordset(p_items) as x(product_id integer, qty integer)
    group by product_id order by product_id
  loop
    if v_item.product_id is null or v_item.qty < 1 or v_item.qty > 1000000 then raise exception 'Invalid quantity'; end if;
    select * into v_product from public.products where id = v_item.product_id and not archived for update;
    if not found then raise exception 'Product unavailable'; end if;
    if private.free_stock(v_item.product_id) < v_item.qty then raise exception 'Not enough free stock for %', v_product.name; end if;
    v_price := case when v_product.bulk_price > 0 then v_product.bulk_price else v_product.retail_price end;
    insert into public.bulk_order_items(order_id,product_id,qty,unit_price) values(v_id,v_item.product_id,v_item.qty,v_price);
    v_total := v_total + v_item.qty * v_price;
  end loop;
  update public.bulk_orders set total_amount = v_total where order_id = v_id;
  insert into public.audit_log(user_id,action) values(auth.uid(),'bulk order #' || v_id);
  return v_id;
end;
$$;

-- Completing an order with items records the sale at the prices quoted on the order.
create or replace function public.complete_bulk_order(p_order_id integer)
returns integer language plpgsql security definer set search_path = '' as $$
declare v_order public.bulk_orders%rowtype; v_sale_id integer;
begin
  if not private.is_active() then raise exception 'Not authorized'; end if;
  select * into v_order from public.bulk_orders where order_id = p_order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if v_order.order_status in ('Completed','Cancelled') then raise exception 'Order is already %', lower(v_order.order_status); end if;
  perform set_config('app.completing_order', 'on', true);
  update public.bulk_orders set order_status = 'Completed' where order_id = p_order_id;
  if exists(select 1 from public.bulk_order_items where order_id = p_order_id) then
    v_sale_id := public.record_sale('bulk', left(v_order.customer_name,100),
      (select jsonb_agg(jsonb_build_object('product_id',product_id,'qty',qty)) from public.bulk_order_items where order_id = p_order_id));
    update public.sale_items si set unit_price = i.unit_price
    from public.bulk_order_items i where si.sale_id = v_sale_id and i.order_id = p_order_id and i.product_id = si.product_id;
    update public.sales set total = (select sum(qty * unit_price) from public.sale_items where sale_id = v_sale_id) where id = v_sale_id;
    update public.bulk_orders set sale_id = v_sale_id where order_id = p_order_id;
  end if;
  perform set_config('app.completing_order', 'off', true);
  insert into public.audit_log(user_id,action) values(auth.uid(),'completed bulk order #' || p_order_id);
  return v_sale_id;
end;
$$;

-- Status edits from the app cannot complete an itemised order (it must go through complete_bulk_order)
-- or reopen a finished one, which would reserve stock again without a check.
create or replace function private.guard_order_status() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.order_status is distinct from old.order_status
     and coalesce(current_setting('app.completing_order', true), '') <> 'on'
     and exists(select 1 from public.bulk_order_items where order_id = new.order_id) then
    if new.order_status = 'Completed' then raise exception 'Use Complete pickup to finish this order'; end if;
    if old.order_status in ('Completed','Cancelled') then raise exception 'This order is closed and cannot be reopened'; end if;
  end if;
  return new;
end;
$$;
create trigger guard_order_status before update on public.bulk_orders
  for each row execute function private.guard_order_status();

-- Alerts: the work moves to a private job so the scheduler can run it without a signed-in user.
create or replace function private.refresh_alerts_job() returns void
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.alerts(type,ref_id,message)
  select 'offline',u.id,'No data from ' || u.name || ' for 10+ minutes'
  from public.storage_units u left join public.temp_logs t on t.unit_id = u.id
  group by u.id,u.name having max(t.logged_at) is null or max(t.logged_at) < now() - interval '10 minutes'
  on conflict (type,ref_id) where status <> 'resolved' do nothing;
  insert into public.alerts(type,ref_id,message)
  select 'low_stock',p.id,'Low stock: ' || p.name
  from public.products p left join public.batches b on b.product_id = p.id
  where not p.archived group by p.id,p.name,p.reorder_level
  having coalesce(sum(b.qty_remaining),0) <= p.reorder_level
  on conflict (type,ref_id) where status <> 'resolved' do nothing;
  update public.alerts a set status='resolved',remarks='Stock replenished'
  where a.type='low_stock' and a.status <> 'resolved'
    and not exists (
      select 1 from public.products p left join public.batches b on b.product_id=p.id
      where p.id=a.ref_id and not p.archived group by p.id,p.reorder_level
      having coalesce(sum(b.qty_remaining),0) <= p.reorder_level
    );
  insert into public.alerts(type,ref_id,message)
  select 'expiry',b.id,p.name || ' batch ' || b.batch_no || ' expires ' || b.expiry::text
  from public.batches b join public.products p on p.id=b.product_id
  where b.qty_remaining > 0 and b.expiry <= private.today() + 30
  on conflict (type,ref_id) where status <> 'resolved' do nothing;
  update public.alerts a set status='resolved',remarks='Batch used up'
  from public.batches b where a.type='expiry' and a.ref_id=b.id and b.qty_remaining=0 and a.status <> 'resolved';
end;
$$;
create or replace function public.refresh_alerts() returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not private.is_active() then raise exception 'Not authorized'; end if;
  perform private.refresh_alerts_job();
end;
$$;

