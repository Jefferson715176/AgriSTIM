revoke all on function public.complete_bulk_order(integer) from public;
grant execute on function public.void_sale(integer,text) to authenticated;
grant execute on function public.create_bulk_order(text,text,date,time,jsonb,text) to authenticated;
grant execute on function public.complete_bulk_order(integer) to authenticated;

-- Hourly refresh (skipped where pg_cron is unavailable, e.g. the local test database).
do $$ begin
  if exists(select 1 from pg_available_extensions where name = 'pg_cron') then
    create extension if not exists pg_cron;
    perform cron.schedule('agristim-refresh-alerts', '0 * * * *', 'select private.refresh_alerts_job()');
  end if;
end $$;
